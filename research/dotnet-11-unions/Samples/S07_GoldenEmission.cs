using System.Numerics;
using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;

namespace Samples;

// SAMPLE 7 — GOLDEN EMISSION for the rewritten UnionStruct, unmanaged case set.
//
// This is the exact shape the generator should PRODUCE when every case type is unmanaged
// and the union is non-generic, i.e. when [FieldOffset] overlap is allowed. S10 is the
// companion for the other branch (generic and/or managed cases => sequential layout) and
// explains the input surface.
//
// The user writes the case types and the "user half": the BCL [Union] plus one partial
// constructor per case. Everything in `#region generated` is the generator's output.
//
// Proves: (1) native exhaustive match, no default arm; (2) 0 B on construct + match;
// (3) `ref` access to a payload; (4) value equality; (5) the type-name / UTF-8 helpers —
// with no Switch/Match delegates, no US0001 analyzer and no CS8509 suppressor.
public static class S07_GoldenEmission
{
    public static void Run()
    {
        Console.WriteLine("[S07] Golden emission (unmanaged cases => explicit overlap)");

        // Construction via constructor or implicit conversion.
        Transform a = new Angle(1.5f);
        Transform p = new Position(new Vector3(3, 4, 0));

        // (1) Native exhaustive switch — NO default arm.
        Console.WriteLine($"  match: {Describe(a)} | {Describe(p)}");

        // (3) ref access straight into the union's overlapped storage — zero copy.
        //     (case types are readonly records, so we write the payload through the ref)
        ref Position slot = ref p.PositionData;
        slot = new Position(new Vector3(13, 4, 0));
        Console.WriteLine($"  after ref mutate: {Describe(p)}");

        // (4) value equality.
        Transform p2 = new Position(new Vector3(13, 4, 0));
        Console.WriteLine($"  equality after mutate: p == p2 -> {p == p2}");

        // (5) type-name helpers, including a DisplayName override.
        Console.WriteLine($"  GetTypeString: {a.GetTypeString()} / {p.GetTypeString()} / {Transform.GetTypeString(Transform.RotationIndex)}");
        Console.WriteLine($"  NullTerminatedMemberNames: \"{System.Text.Encoding.UTF8.GetString(Transform.NullTerminatedMemberNames).Replace("\0", "\\0")}\"");

        // (2) zero-allocation construct + match.
        for (int i = 0; i < 1000; i++) _ = Score(new Angle(i));   // warm up
        long before = GC.GetAllocatedBytesForCurrentThread();
        double acc = 0;
        for (int i = 0; i < 1_000_000; i++)
        {
            Transform t = (i & 1) == 0 ? new Angle(i) : new Position(new Vector3(i, 0, 0));
            acc += Score(t);
        }
        long bytes = GC.GetAllocatedBytesForCurrentThread() - before;
        Console.WriteLine($"  sizeof(Transform) = {Unsafe.SizeOf<Transform>()} bytes; 1M construct+match = {bytes:N0} bytes (acc={acc:F0})\n");
    }

    static string Describe(Transform t) => t switch
    {
        Angle x => $"Angle({x.Value})",
        Position x => $"Position({x.Value.X},{x.Value.Y},{x.Value.Z})",
        Rotation x => $"Rotation({x.Value})",
    };

    static double Score(Transform t) => t switch
    {
        Angle x => x.Value,
        Position x => x.Value.X,
        Rotation x => x.Value.W,
    };
}

// ---- user-declared case types ----
public readonly record struct Angle(float Value);
public readonly record struct Position(Vector3 Value);
public readonly record struct Rotation(Quaternion Value);

// ---- USER HALF: this is everything the user writes ----
[Union]
public partial struct Transform
{
    public partial Transform(Angle value);

    public partial Transform(Position value);

    [UnionStruct.UnionCase(DisplayName = "Quaternion rotation")]
    public partial Transform(Rotation value);
}

#region generated by UnionStruct (target)
[StructLayout(LayoutKind.Explicit)]   // all case types unmanaged & union non-generic => overlap
public partial struct Transform : IUnion, IEquatable<Transform>
{
    public const int CaseCount = 3;
    public const int AngleIndex = 0;
    public const int PositionIndex = 1;
    public const int RotationIndex = 2;

    // Public and read-only: feeds the type-name helpers and index-based UI, and is the
    // fastest match for large payloads in hot loops (S11) — but unlike the native type
    // switch, a switch on it is not checked for exhaustiveness.
    [FieldOffset(0)] public readonly int CaseIndex;

    // Public so callers can `ref` a payload. Overlapped: writing the wrong case's field
    // corrupts the active one — the library's deliberate memory-unsafety.
    [FieldOffset(4)] public Angle AngleData;
    [FieldOffset(4)] public Position PositionData;
    [FieldOffset(4)] public Rotation RotationData;

    // Implementing halves of the user's partial constructors. `this = default` first,
    // because overlapped fields cannot each be definitely assigned.
    public partial Transform(Angle value) { this = default; CaseIndex = AngleIndex; AngleData = value; }
    public partial Transform(Position value) { this = default; CaseIndex = PositionIndex; PositionData = value; }
    public partial Transform(Rotation value) { this = default; CaseIndex = RotationIndex; RotationData = value; }

    // Convenience implicit conversions. These do NOT register cases (only constructors do).
    public static implicit operator Transform(Angle value) => new(value);
    public static implicit operator Transform(Position value) => new(value);
    public static implicit operator Transform(Rotation value) => new(value);

    // IUnion contract — boxes only if a caller explicitly reads it.
    public readonly object Value => CaseIndex switch { AngleIndex => AngleData, PositionIndex => PositionData, _ => RotationData };

    // Non-boxing access pattern — the compiler lowers pattern matching through these.
    // `readonly` so a `ref readonly` / `in` receiver never needs a defensive copy.
    public readonly bool TryGetValue(out Angle value) { value = AngleData; return CaseIndex == AngleIndex; }
    public readonly bool TryGetValue(out Position value) { value = PositionData; return CaseIndex == PositionIndex; }
    public readonly bool TryGetValue(out Rotation value) { value = RotationData; return CaseIndex == RotationIndex; }

    // Equality (the language does not synthesize this for unions).
    public readonly bool Equals(Transform other) => CaseIndex == other.CaseIndex && CaseIndex switch
    {
        AngleIndex => AngleData.Equals(other.AngleData),
        PositionIndex => PositionData.Equals(other.PositionData),
        RotationIndex => RotationData.Equals(other.RotationData),
        _ => true,
    };

    public override readonly bool Equals(object? obj) => obj is Transform o && Equals(o);

    public override readonly int GetHashCode() => CaseIndex switch
    {
        AngleIndex => HashCode.Combine(CaseIndex, AngleData),
        PositionIndex => HashCode.Combine(CaseIndex, PositionData),
        RotationIndex => HashCode.Combine(CaseIndex, RotationData),
        _ => CaseIndex,
    };

    public static bool operator ==(Transform left, Transform right) => left.Equals(right);
    public static bool operator !=(Transform left, Transform right) => !left.Equals(right);

    public override readonly string ToString() => CaseIndex switch
    {
        AngleIndex => $"Angle {{ Value = {AngleData} }}",
        PositionIndex => $"Position {{ Value = {PositionData} }}",
        RotationIndex => $"Quaternion rotation {{ Value = {RotationData} }}",
        _ => "<invalid>",
    };

    // Type-name helpers: the case type's name, or its DisplayName.
    public static string GetTypeString(int caseIndex) => caseIndex switch
    {
        AngleIndex => "Angle",
        PositionIndex => "Position",
        RotationIndex => "Quaternion rotation",
        _ => throw new System.Diagnostics.UnreachableException($"Invalid case index: {caseIndex}."),
    };

    public readonly string GetTypeString() => GetTypeString(CaseIndex);

    public static ReadOnlySpan<byte> GetTypeAsUtf8Span(int caseIndex) => caseIndex switch
    {
        AngleIndex => "Angle"u8,
        PositionIndex => "Position"u8,
        RotationIndex => "Quaternion rotation"u8,
        _ => throw new System.Diagnostics.UnreachableException($"Invalid case index: {caseIndex}."),
    };

    public readonly ReadOnlySpan<byte> GetTypeAsUtf8Span() => GetTypeAsUtf8Span(CaseIndex);

    public static ReadOnlySpan<byte> NullTerminatedMemberNames => "Angle\0Position\0Quaternion rotation\0"u8;
}
